#!/usr/bin/env node
// Regenerates the offline bundle in offline/ from app.html. No dependencies. Run from repo root:
//   node tools/build-offline.mjs
// offline/app.html is app.html with the pinned CDN <script> tags pointed at offline/libs/.
// Libraries are downloaded only when missing, and are always verified against the SHA-256 below.
// To upgrade Skulpt: change the version in app.html AND the url/sha256 entries here, delete offline/libs/*.js, rerun.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { pathToFileURL } from "node:url";

export const OUT_DIR = "offline", LIB_DIR = "offline/libs";
export const LIBS = [
  { file: "skulpt.min.js", url: "https://cdn.jsdelivr.net/npm/skulpt@1.2.0/dist/skulpt.min.js", sha256: "1a319d8eedf314dba5af2444313e3cf2ac072a335df0f5100277e8f49b64eae9" },
  { file: "skulpt-stdlib.js", url: "https://cdn.jsdelivr.net/npm/skulpt@1.2.0/dist/skulpt-stdlib.js", sha256: "e3ecccbc17c6164d19ed3c5561aaaeb752c38c8efa2d88b62b5fb7a7e1b086a7" },
  { file: "LICENSE-skulpt.txt", url: "https://cdn.jsdelivr.net/npm/skulpt@1.2.0/LICENSE", sha256: "e407544486b5cff8bdb1faa9930ae5d980fd363d1003d3a032f9915674da0fa9" },
];
const BANNER = "<!-- GENERATED by tools/build-offline.mjs from ../app.html. Do not edit; edit app.html and rerun the script. -->";

export const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

// Pure transform shared with tools/check.mjs. Output always uses LF line endings.
export function offlineHtml(appHtml) {
  let s = appHtml.replace(/\r\n/g, "\n");
  for (const { file, url } of LIBS.filter((l) => l.file.endsWith(".js"))) {
    const tag = `<script src="${url}"></script>`;
    if (!s.includes(tag)) throw new Error(`app.html no longer contains ${tag}; update LIBS in tools/build-offline.mjs`);
    s = s.replace(tag, `<script src="libs/${file}"></script>`);
  }
  const ext = s.match(/<script[^>]*\ssrc="(https?:[^"]+)"/);
  if (ext) throw new Error(`app.html loads an external script not covered by LIBS: ${ext[1]}`);
  if (!s.includes("<head>\n")) throw new Error("app.html has no <head> line");
  return s.replace("<head>\n", `<head>\n${BANNER}\n`);
}

async function main() {
  mkdirSync(LIB_DIR, { recursive: true });
  for (const { file, url, sha256: want } of LIBS) {
    const path = `${LIB_DIR}/${file}`;
    if (existsSync(path) && sha256(readFileSync(path)) === want) continue;
    console.log(`downloading ${url}`);
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    if (sha256(buf) !== want) throw new Error(`${url}: SHA-256 mismatch, refusing to vendor it`);
    writeFileSync(path, buf);
  }
  writeFileSync(`${OUT_DIR}/app.html`, offlineHtml(readFileSync("app.html", "utf8")));
  console.log(`OK: ${OUT_DIR}/app.html regenerated; libraries verified.`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main().catch((e) => { console.error("FAIL:", e.message); process.exit(1); });
